#include "libft.h"

int	ft_sqrt(int nb)
{
	int	rc;

	if (nb <= 0)
		return (0);
	rc = 1;
	while (rc <= 46340 && rc * rc < nb)
		rc++;
	if (rc * rc > nb)
		rc--;
	return (rc);
}
